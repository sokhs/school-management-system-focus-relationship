-- students table
create table students (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    first_name varchar(100) not null,
    last_name varchar(100) not null,

    gender varchar(20),
    phone varchar(20),

    address varchar(255),

    status varchar(30) not null default 'ACTIVE',

    constraint chk_student_status check (status in ('ACTIVE', 'INACTIVE', 'GRADUATED', 'SUSPENDED', 'TRANSFERRED'))
);

-- classroom table
create table classrooms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name varchar(100) not null,
    grade varchar(100) not null,

    academic_year_id bigint default 0,

    capacity int,

    status varchar(20) not null default 'ACTIVE',

    -- make status accept only Active and Inactive
    constraint chk_classroom_status check (status in ('ACTIVE', 'INACTIVE'))
);

-- subjects table
create table subjects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    subject_code varchar(30) not null,
    name varchar(100) not null,

    description varchar(255),

    status varchar(20) not null default 'ACTIVE',

    -- make subject_code to UNIQUE
    constraint uk_subject_code UNIQUE (subject_code),

    -- make status accept only Active and Inactive
    constraint chk_subject_status check (status in ('ACTIVE', 'INACTIVE'))
);

-- enrollment table
create table enrollments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    student_id bigint not null,
    classroom_id bigint not null,

    enrollment_date Date not null,

    status varchar(30) not null default 'ACTIVE',

    remark varchar(255),

    -- check status accept only Active or Inactive
    constraint chk_enrollment_status check (status in ('ACTIVE', 'COMPLETED', 'TRANSFERRED', 'DROPPED')),

    -- make relationship between Enrollment and Student
    constraint fk_enrollment_student
        foreign key (student_id)
        references students(id)
        on update cascade
        on delete restrict,

    -- make relationship between Enrollment and Classroom
    constraint fk_enrollment_classroom
                         foreign key (classroom_id)
                         references classrooms(id)
                         on update cascade
                         on delete restrict,

    -- make student_id and classroom_id are UNIQUE
    constraint uk_student_classroom unique (student_id, classroom_id)
);

create table attendance (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    student_id bigint not null,
    classroom_id bigint not null,

    attendance_date DATE DEFAULT CURRENT_DATE,

    status varchar(20) not null,

    remarks varchar(255),

    constraint fk_attendance_student
                        foreign key (student_id)
                        references students(id)
                        on update cascade
                        on delete restrict,

    constraint fk_attendance_classroom
                        foreign key (classroom_id)
                        references classrooms(id)
                        on update cascade
                        on delete restrict,

    constraint chk_attendance_status check (status in ('PRESENT', 'ABSENT', 'LATE', 'EXCUSED'))
);

-- parents table
create table parents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    first_name varchar(100) not null,
    last_name varchar(100) not null,
    phone varchar(20) not null,

    email varchar(100),
    address varchar(255),

    occupation varchar(50)
);

-- student_parents table
create table student_parents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    student_id bigint not null,
    parent_id bigint not null,

    relationship_type varchar(30) not null,

    is_primary_guardian boolean not null default false,

    -- make relationship between Student_parents and Students
    constraint fk_student_parent_student
                             foreign key (student_id)
                             references students(id)
                             on update cascade
                             on delete restrict,

    -- make relationship between Student_parent and Students
    constraint fk_student_parent_parent
                             foreign key (parent_id)
                             references parents(id)
                             on update cascade
                             on delete restrict,

    -- make student_id and parent_id are UNIQUE
    constraint uk_student_parent unique (student_id, parent_id)
);

































